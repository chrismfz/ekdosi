 ELSE
 BEGIN
  IF(XINVOICE_ID IS NOT NULL) THEN
   DELETE FROM INVLINES WHERE PRODUCT_ID = :XPRODUCT_ID AND INVOICE_ID = :XINVOICE_ID;
  ELSE
   DELETE FROM INVLINES WHERE PRODUCT_ID = :XPRODUCT_ID AND INVOICE_ID IS NULL;
 END

end ^

