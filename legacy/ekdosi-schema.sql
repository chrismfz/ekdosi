ALTER PROCEDURE CALCULATE_INVOICE_VALUES (INVOICE_ID INTEGER)
AS 
DECLARE VARIABLE PRICE_VAL NUMERIC(18,2);
DECLARE VARIABLE PRICEWVAT_VAL NUMERIC(18,2);
begin
  SELECT SUM(PRICE), SUM(PRICEWVAT) FROM INVLINES WHERE INVOICE_ID = :INVOICE_ID INTO :PRICE_VAL, :PRICEWVAT_VAL;

  UPDATE INVOICE SET PRICE = :PRICE_VAL, PRICEWVAT = :PRICEWVAT_VAL WHERE INVOICE_ID = :INVOICE_ID;
  suspend;
end ^

ALTER PROCEDURE CALCULATE_VAT_FOR_INVOICE (INVOICE_ID INTEGER)
RETURNS (VAT_PERCENT PERCENTAGE,
VAL CURRENCY)
AS 
begin
 FOR
  SELECT VATPERCENT, SUM((INVLINES.PRICEWVAT - INVLINES.PRICE)- ((INVLINES.PRICEWVAT - INVLINES.PRICE) * (CAST(INVOICE.DISCOUNT AS NUMERIC(14,4))/100) ) ) FROM INVLINES
   INNER JOIN INVOICE ON INVLINES.INVOICE_ID = INVOICE.INVOICE_ID
   WHERE INVLINES.INVOICE_ID = :INVOICE_ID
   GROUP BY VATPERCENT
   INTO :VAT_PERCENT, :VAL DO
  suspend;
end ^

