ALTER PROCEDURE FILL_PRDESCR_INVLINES AS 
declare variable ID INTEGER;
declare variable PR_ID INTEGER;
declare variable METRIC_ID INTEGER;
declare variable DESCR VARCHAR(120);
begin

 FOR SELECT INVLINE_ID, PRODUCT_ID FROM INVLINES INTO :ID, :PR_ID DO
 BEGIN
  SELECT PRODUCT.DESCRIPTION_SHORT, METRIC_ID FROM PRODUCT WHERE PRODUCT_ID = :PR_ID INTO :DESCR, :METRIC_ID;
   UPDATE INVLINES SET PRODUCT_DESCR = :DESCR WHERE INVLINE_ID = :ID;

   UPDATE INVLINES SET METRIC_UNIT = (SELECT NAME FROM METRIC_UNITS WHERE METRIC_ID = :METRIC_ID) WHERE INVLINE_ID = :ID;
 END
end ^

